#!/usr/bin/env node
/**
 * pw-session — headed Playwright session capture for challenge-protected targets.
 *
 * WHY: many targets sit behind interactive edge challenges, device fingerprinting
 * or bot detection that reject plain HTTP clients. This launches a real (headed)
 * browser through your proxy so a human can sign in, then captures the resulting
 * session so the rest of your testing is reproducible with bin/hit.
 *
 * It does NOT automate login. You sign in by hand, because automating it is both
 * fragile and, on some programs, indistinguishable from the automated scanning
 * the rules forbid. The tool captures the session a human created.
 *
 * Configuration (environment variables):
 *   HARNESS_CONF   path to harness.conf (default ~/.config/engagement-harness/harness.conf)
 *   START_URL      first page to open
 *   WHO            identity label, e.g. A (default A)
 *   PW_EXECUTABLE  optional browser path (e.g. system Chrome)
 *
 * Usage:
 *   START_URL=https://app.example.com/ WHO=A bin/pw-session.js
 *   WHO=B bin/pw-session.js
 *
 * Outputs (under STATE_DIR/cookies/):
 *   <WHO>.jar         Netscape cookie jar, for bin/hit
 *   <WHO>.token       first bearer token seen, for bin/hit
 *   <WHO>.useragent   the UA used, so replays match
 *   <WHO>.storage.json  localStorage + sessionStorage
 *   capture-<WHO>.jsonl in-scope request/response metadata
 *
 * Ctrl-C to flush and close.
 */
const { chromium } = require('playwright');
const fs = require('fs');
const os = require('os');
const path = require('path');

function loadConf(p) {
  const conf = {};
  if (!fs.existsSync(p)) return conf;
  for (let line of fs.readFileSync(p, 'utf8').split('\n')) {
    line = line.replace(/#.*$/, '').trim();
    if (!line || !line.includes('=')) continue;
    const i = line.indexOf('=');
    conf[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return conf;
}

const CONF_PATH = process.env.HARNESS_CONF ||
  path.join(os.homedir(), '.config/engagement-harness/harness.conf');
const conf = loadConf(CONF_PATH);

const STATE_DIR = (conf.STATE_DIR || path.join(os.homedir(), '.local/state/engagement-harness'))
  .replace(/^~/, os.homedir());
const COOKIE_DIR = path.join(STATE_DIR, 'cookies');
fs.mkdirSync(COOKIE_DIR, { recursive: true });

const WHO = String(process.env.WHO || 'A');
const PROXY = conf.PROXY || 'http://127.0.0.1:8080';
const START_URL = process.env.START_URL || 'about:blank';

const patterns = (conf.SCOPE_HOSTS || '').split(/\s+/).filter(Boolean);
const inScope = (host) => patterns.some((p) => {
  const rx = new RegExp('^' + p.replace(/[.+?^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '.*') + '$', 'i');
  return rx.test(host);
});

const BASE_UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';
const UA = conf.USER_AGENT_TAG ? `${BASE_UA} ${conf.USER_AGENT_TAG}` : BASE_UA;

(async () => {
  const ctx = await chromium.launchPersistentContext(path.join(STATE_DIR, `profile-${WHO}`), {
    headless: false,
    ...(process.env.PW_EXECUTABLE ? { executablePath: process.env.PW_EXECUTABLE } : {}),
    proxy: { server: PROXY },
    ignoreHTTPSErrors: true,
    userAgent: UA,
    viewport: null,
    args: ['--disable-blink-features=AutomationControlled'],
  });

  const page = ctx.pages()[0] || (await ctx.newPage());

  const capPath = path.join(STATE_DIR, `capture-${WHO}.jsonl`);
  const cap = fs.createWriteStream(capPath, { flags: 'a' });
  const tokens = new Set();
  const log = (r) => cap.write(JSON.stringify(r) + '\n');

  page.on('request', (req) => {
    let host = ''; try { host = new URL(req.url()).hostname; } catch (_) { return; }
    if (!inScope(host)) return;
    const h = req.headers();
    log({ t: new Date().toISOString(), who: WHO, dir: 'req', method: req.method(),
          url: req.url(), headers: h, body: req.postData() || null });
    if (h['authorization']) tokens.add(String(h['authorization']).replace(/^Bearer\s+/i, '').trim());
  });

  page.on('response', (res) => {
    let host = ''; try { host = new URL(res.url()).hostname; } catch (_) { return; }
    if (!inScope(host)) return;
    log({ t: new Date().toISOString(), who: WHO, dir: 'res', status: res.status(), url: res.url() });
  });

  const dump = async () => {
    try {
      const cookies = await ctx.cookies();
      const lines = ['# Netscape HTTP Cookie File', '# generated by pw-session'];
      for (const c of cookies) {
        lines.push([c.domain, c.domain.startsWith('.') ? 'TRUE' : 'FALSE', c.path,
          c.secure ? 'TRUE' : 'FALSE', Math.floor(c.expires || 0), c.name, c.value].join('\t'));
      }
      fs.writeFileSync(path.join(COOKIE_DIR, `${WHO}.jar`), lines.join('\n') + '\n');

      try {
        const storage = await page.evaluate(() => ({
          localStorage: { ...localStorage }, sessionStorage: { ...sessionStorage },
        }));
        fs.writeFileSync(path.join(COOKIE_DIR, `${WHO}.storage.json`), JSON.stringify(storage, null, 2));
        for (const k of ['token', 'access_token', 'accessToken']) {
          const v = storage.localStorage && storage.localStorage[k];
          if (v) tokens.add(String(v).replace(/^Bearer\s+/i, '').trim());
        }
      } catch (_) { /* page not on target yet */ }

      const raw = [...tokens].map((t) => t.trim()).filter(Boolean);
      if (raw.length) fs.writeFileSync(path.join(COOKIE_DIR, `${WHO}.token`), raw.join('\n') + '\n');
      fs.writeFileSync(path.join(COOKIE_DIR, `${WHO}.useragent`), UA + '\n');
      console.log(`[flush] ${WHO}: ${cookies.length} cookies, ${tokens.size} token(s) → ${capPath}`);
    } catch (e) {
      console.error('[flush] failed:', e.message);
    }
  };

  console.log(`[pw] identity=${WHO}  proxy=${PROXY}`);
  console.log(`[pw] sign in by hand in the window, then Ctrl-C here to flush.`);

  if (START_URL !== 'about:blank') {
    await page.goto(START_URL, { waitUntil: 'domcontentloaded' })
      .catch((e) => console.error('[pw] goto:', e.message));
  }

  const iv = setInterval(dump, 5000);
  process.on('SIGINT', async () => { clearInterval(iv); await dump(); await ctx.close(); process.exit(0); });
  ctx.on('close', () => { clearInterval(iv); dump(); });
})();
